DROP DATABASE IF EXISTS rapp_users;

CREATE DATABASE rapp_users;
USE rapp_users;

-- 1. Cria a tabela 'reps' PRIMEIRO (pois ela será referenciada)
CREATE TABLE reps (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Cria a tabela 'users' já com a FK integrada
CREATE TABLE users (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL,
    republica VARCHAR(100),
    rep_id INT,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_moradores FOREIGN KEY (rep_id)
        REFERENCES reps (id)
        ON DELETE CASCADE ON UPDATE CASCADE
);

